// Builds every course in content/courses.json into .content/<slug>/ (ADR-0006).
// Usage: pnpm content:build [--no-diagrams]
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { buildCourse, mermaidSources } from "../src/content/build-course";
import { coursesFileSchema } from "../src/content/config";
import { renderDiagrams } from "../src/content/diagrams";
import type { SearchRecord } from "../src/content/types";
import type { DiagramRenders } from "../src/content/types";

const root = process.cwd();
const outRoot = path.join(root, ".content");
const skipDiagrams = process.argv.includes("--no-diagrams");

function writeJson(file: string, data: unknown) {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, JSON.stringify(data, null, 1) + "\n");
}

const { courses } = coursesFileSchema.parse(
  JSON.parse(readFileSync(path.join(root, "content/courses.json"), "utf8")),
);
rmSync(outRoot, { recursive: true, force: true });
const searchRecords: (SearchRecord & { pageLabel: string })[] = [];

for (const course of courses) {
  const started = Date.now();
  const markdown = readFileSync(path.join(root, course.source), "utf8");
  let renders: DiagramRenders = {};
  if (!skipDiagrams) {
    renders = await renderDiagrams(mermaidSources(markdown), {
      cacheDir: path.join(root, ".cache"),
      outDir: path.join(root, "public/diagrams"),
      log: (m) => console.log(`  ${m}`),
    });
  }
  const build = await buildCourse(markdown, course, renders);
  const dir = path.join(outRoot, course.slug);
  writeJson(path.join(dir, "manifest.json"), build.manifest);
  for (const page of build.pages) writeJson(path.join(dir, "pages", `${page.key}.json`), page);
  writeJson(path.join(dir, "glossary.json"), build.glossary);
  writeJson(path.join(dir, "cards.json"), build.cards);
  writeJson(path.join(dir, "diagrams.json"), build.diagrams);
  writeJson(path.join(dir, "search.json"), build.search);
  const labels = new Map(build.manifest.pages.map((p) => [p.key, p.label]));
  for (const r of build.search)
    searchRecords.push({ ...r, pageLabel: labels.get(r.pageKey) ?? "" });

  const m = build.manifest;
  const published = m.pages.filter((p) => p.status === "published").length;
  console.log(
    `✓ ${course.slug}: ${published} published, ${m.pages.length - published} coming soon, ` +
      `${build.diagrams.length} diagrams (${Object.keys(renders).length} rendered), ` +
      `${build.cards.length} cards, ${build.glossary.length} terms — ${Date.now() - started} ms`,
  );
  for (const w of m.warnings) console.warn(`  ⚠ ${w}`);
}

// Generated registry: lets server code import manifests statically (works on Workers).
const registry =
  `// Generated by scripts/content-build.ts — do not edit.\n` +
  courses
    .map(
      (c, i) =>
        `import m${i} from "./${c.slug}/manifest.json";\nimport g${i} from "./${c.slug}/glossary.json";\nimport c${i} from "./${c.slug}/cards.json";`,
    )
    .join("\n") +
  `\nimport type { CourseManifest, GlossaryEntry, Card } from "../src/content/types";\n` +
  `export const generated: Record<string, { manifest: CourseManifest; glossary: GlossaryEntry[]; cards: Card[] }> = {\n` +
  courses
    .map(
      (c, i) =>
        `  ${JSON.stringify(c.slug)}: { manifest: m${i} as unknown as CourseManifest, glossary: g${i} as unknown as GlossaryEntry[], cards: c${i} as unknown as Card[] },`,
    )
    .join("\n") +
  `\n};\n`;
writeFileSync(path.join(outRoot, "index.ts"), registry);

// Full-text search (ADR-0008): a static, chunked Pagefind index, one record per section.
const pagefind = await import("pagefind");
const { index } = await pagefind.createIndex({});
if (!index) throw new Error("Pagefind could not create an index");
for (const r of searchRecords) {
  await index.addCustomRecord({
    url: r.url,
    content: r.text,
    language: "en",
    meta: { title: r.title, page: r.pageLabel ? `${r.pageLabel}: ${r.pageTitle}` : r.pageTitle },
  });
}
const outputPath = path.join(root, "public/pagefind");
rmSync(outputPath, { recursive: true, force: true });
await index.writeFiles({ outputPath });
await pagefind.close();
console.log(`✓ search index: ${searchRecords.length} sections`);
